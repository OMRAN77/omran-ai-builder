/* reply-style.js — v-rich-reply (لقطات المالك ١٣ أكتوبر: ChatGPT يجيب «عطني معلومات عن الامارات والسعودية» في ثوانٍ بعناوين
   وصور حقيقيّة تحت كلّ دولة وبطاقة أسئلة في آخره، وعندنا GPT-6 Astra «فكّر لمدّة 44 ث» ثمّ نقاط بلا صورة — «اريد الردود اقوى
   من هذي وفيها صور… دقق على الأسلوب… والسرعة في الرد»):
   - isInfoAsk: طلب معلومات أو نبذة عن شيء. يُستعمل لثلاثة: تفكير المالك المنخفض فيه (owner-think)، وتخطّي الخرائط في بحثه
     (الخرائط تعرف المحلّات لا الحقائق، وكانت تسبق كلّ بحث محلّيّ بنداء يصل ٩ ث)، وملاحظة الشكل أدناه.
   - RICH_REPLY_NOTE: شكل ChatGPT — افتتاح، عناوين، صور [[IMG: …]] تجلبها الواجهة، جدول للمقارنة، وختام بخيارات [[OPT]].
   - withSocialGrace: التواصل الاجتماعيّ لا يؤخّر نتيجة الويب أكثر من مهلة قصيرة بعد وصولها (سلسلته قد تبلغ ٣٦ ث). */

const INFO_RE = /(?:^|[\s،,.:؛()«»"'-])(?:و|ف)?(?:ب|عن\s+)?(?:معلومات|معلومه|معلومة|نبذ[ةه]|حقائق|عرّفني|عرفني|حدّثني\s+عن|حدثني\s+عن|كلّمني\s+عن|كلمني\s+عن|احكي\s+لي\s+عن|احكيلي\s+عن|tell\s+me\s+about|facts\s+about|information\s+about|info\s+about|overview\s+of)(?=$|[\s،,.:؛()«»"'?؟!-])/i;
const PERSON_RE = /(?:^|[\s،,.:؛()«»"'-])(?:من|مين|منو)\s+(?:هو|هي)(?=$|[\s،,.:؛()«»"'?؟!-])|\bwho\s+(?:is|was)\b/i;
const COMPARE_RE = /(?:^|[\s،,.:؛()«»"'-])(?:و|ف)?(?:قارن|قارني|مقارنة|الفرق\s+بين|وش\s+الفرق|شو\s+الفرق|ما\s+الفرق|compare|difference\s+between)(?=$|[\s،,.:؛()«»"'?؟!-])/i;

/** طلب معلومات/نبذة عن شيء (أو استعلام بحث بـsite:) — لا تحليل ولا شراء. */
function isInfoAsk(s) {
  const t = String(s || '');
  if (!t.trim() || t.length > 400) return false;
  return /(?:^|\s)site:/i.test(t) || INFO_RE.test(t);
}
/** الردّ يستحقّ شكل ChatGPT الغنيّ: طلب معلومات، أو «من هو»، أو مقارنة. */
function wantsRichReply(s) {
  const t = String(s || '');
  if (!t.trim() || t.length > 400) return false;
  return INFO_RE.test(t) || PERSON_RE.test(t) || COMPARE_RE.test(t);
}

const RICH_REPLY_NOTE = '\n\n[شكل هذا الردّ — طلب معلومات أو نبذة أو مقارنة]:\n' +
  '- سطر افتتاحيّ واحد بالزبدة، ثمّ عنوان «## » لكلّ موضوع رئيسيّ مع رمز أو علم يناسبه، وتحته أقسام «### » قصيرة ونقاط تبدأ بعنوان **عريض**. المقارنة بين اثنين أو أكثر جدول ماركداون كامل (رأس وسطر فاصل).\n' +
  '- صور حقيقيّة: تحت عنوان كلّ موضوع رئيسيّ مباشرةً سطر وحده بهذه الصيغة حرفيًّا: [[IMG: اسم١ | اسم٢ | اسم٣]] — من ٢ إلى ٤ أشياء محدّدة مشهورة تُصوَّر (معلم، مبنى، مدينة، شخص، طبق، حيوان، منتج) بأسمائها الصريحة لا كلمات عامّة، وبعد كلّ اسم اسمه الإنجليزيّ بعد « / » إن عرفته. مثال: [[IMG: برج خليفة / Burj Khalifa | مسجد الشيخ زايد الكبير / Sheikh Zayed Grand Mosque | حي الفهيدي / Al Fahidi]]. الواجهة تجلب صورها وتعرضها معرضًا: لا تكتب روابط صور ولا تشرح هذه الصيغة.\n' +
  '- الختام: سؤال متابعة واحد قصير عمّا يريد التعمّق فيه، وتحته خياراته حرفيًّا [[OPT]]خيار١|خيار٢|خيار٣|خيار٤[[/OPT]]. وإن احتجت سؤالين (الجانب ثمّ النطاق) فكلّ سؤال في سطر ينتهي بـ«؟» وتحته [[OPT]] الخاصّ به — يصيران بطاقة واحدة يرسلها بزرّ. هذا الختام مسموح هنا استثناءً من منع الخاتمة.\n' +
  '- السرعة: بحث واحد بعبارة جامعة يكفي هنا، وإن احتجت أكثر من أداة فاطلبها كلّها معًا في الجولة نفسها؛ ولا fetch_page إلّا لرابط ذكره المستخدم.';

const SOCIAL_GRACE_MS = 1500;
/** نتيجة الويب أوّلًا، ثمّ التواصل إن وصل خلال مهلة قصيرة بعدها — وإلّا يُكمل الردّ بالويب وحده (null = لا قسم تواصل). */
async function withSocialGrace(webP, socialP, ms) {
  const soc = Promise.resolve(socialP).catch(() => null);
  const web = await webP;
  let timer = null;
  const late = new Promise((r) => { timer = setTimeout(() => r(null), ms == null ? SOCIAL_GRACE_MS : ms); });
  const social = await Promise.race([soc, late]);
  clearTimeout(timer);
  return [web, social];
}

module.exports = { isInfoAsk, wantsRichReply, RICH_REPLY_NOTE, withSocialGrace, SOCIAL_GRACE_MS, INFO_RE };
