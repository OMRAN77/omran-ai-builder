// Google Places يرجع رابطًا محشوًّا بـg_mp ومعرّفات بروتوبف طويلة، وكان النموذج
// يلصقها حرفيًّا في الردّ. نقصّها من ناتج الأداة قبل أن يراها.
function cleanLink(u) {
  let t = String(u == null ? '' : u).trim();
  if (!t) return '';
  const cid = t.match(/[?&]cid=(\d+)/);
  if (cid) return 'https://maps.google.com/?cid=' + cid[1];
  t = t.replace(/[&?](?:g_mp|ved|entry|hl|gl|sa|source|utm_[a-z]+)=[^&\s)]*/gi, '');
  if (t.length > 130) {
    try { const U = new URL(t); t = U.origin + U.pathname; } catch (e) { t = t.slice(0, 130); }
  }
  return t.replace(/[?&]+$/, '');
}

