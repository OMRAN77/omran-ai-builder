const LETTER = '[\\p{L}\\p{M}]';

function parse(text) {
  const pairs = [];
  for (const raw of text.split('\n')) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const i = line.indexOf('=');
    if (i < 0) continue;
    const from = line.slice(0, i).trim();
    const to = line.slice(i + 1).trim();
    if (from && to) pairs.push([from, to]);
  }
  return pairs.sort((a, b) => b[0].length - a[0].length); // العبارة قبل كلماتها
}

const escape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const RULES = parse(WORDS).map(([from, to]) => ({
  from, to,
  re: new RegExp(`(?<!${LETTER})([وفبلك]?)${escape(from).replace(/ /g, '\\s+')}(?!${LETTER})`, 'gu'),
}));

// النصّ الذي يقرؤه الصوت العربيّ. غير العربيّ يمرّ كما هو.
function apply(text) {
  if (!text) return text;
  let out = String(text);
  for (const r of RULES) out = out.replace(r.re, (m, prefix) => prefix + r.to);
  return out;
}

