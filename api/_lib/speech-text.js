// v-tts-no-markdown (المالك ٣٠ أكتوبر، لقطة ردّ فيه «**مسجّل الصوت**»: «المتحدّث الحين يقول كل مرّة نجمة نجمة… يردّد على هذا الكلام»):
// «استمع» يرسل نصّ الردّ كما خزّنته المحادثة، بعلامات التنسيق. الصوت العربيّ يقرأ الرمز «*» كلمةً («نجمة»)، وكذلك # و| والروابط
// حرفًا حرفًا والرموز التعبيريّة بأسمائها. هنا يصير النصّ كلامًا فقط قبل أيّ صوت: نصّ الرابط بلا عنوانه، والعناوين والقوائم
// والجداول والاقتباس بلا رموزها. ما يراه المستخدم لا يتغيّر.

function speechText(input) {
  let s = String(input || '');
  s = s.replace(/!\[[^\]]*\]\([^)]*\)/g, ' ')                       // صورة markdown: لا تُقرأ
    .replace(/\[([^\]\n]+)\]\((?:https?:\/\/|www\.)[^)\s]*\)/g, '$1')  // [النصّ](الرابط) ⇐ النصّ
    .replace(/<?(?:https?:\/\/|www\.)[^\s<>()]+>?/g, ' ')               // رابط مكشوف: لا يُقرأ حرفًا حرفًا
    .replace(/```[^\n]*\n?/g, ' ')                                      // أسوار الكود
    .replace(/`+/g, '')
    .replace(/^[ \t]*(?:[-*_]\s*){3,}$/gm, ' ')                         // خطّ فاصل
    .replace(/^[ \t]{0,3}#{1,6}[ \t]+/gm, '')                           // عنوان
    .replace(/^[ \t]*>+[ \t]?/gm, '')                                   // اقتباس
    .replace(/^[ \t]*(?:[-*+•▪◦●]|\d+[.)])[ \t]+/gm, (m) => (/\d/.test(m) ? m : '')) // نقطة القائمة؛ رقمها يبقى
    .replace(/^[ \t]*\|?[ \t:]*-{2,}[ \t:|-]*$/gm, ' ')                 // سطر فاصل الجدول
    .replace(/[ \t]*\|[ \t]*/g, '، ')                                   // خلايا الجدول
    .replace(/\*+|_{2,}|~{2,}/g, '')                                    // عريض ومائل ومشطوب
    .replace(/[\p{Extended_Pictographic}\p{Emoji_Modifier}\u{1F1E6}-\u{1F1FF}\u{FE0F}\u{200D}\u{20E3}]/gu, '') // الرموز التعبيريّة
    .replace(/^[\s،,]+|[\s،,]+$/gm, '')                                 // فواصل يتيمة في طرف السطر
    .replace(/[ \t]{2,}/g, ' ')
    // v-hala-wallah (المالك: «أوّل كلمة هلا والله… ضعيفة»): بلا حركات يقرؤها الصوت فصيحةً «هلّا والله» (أداة تحضيض، وكسرة
    // الجلالة)؛ بحركاتها «هَلا وَاللهْ» كما تُقال. التحيّة في تعريف مها وعبدالله وفي ردودهما ومكالمتهما.
    .replace(/(^|[^\p{L}\p{M}])هلا(\s+)والله(?![\p{L}\p{M}])/gmu, '$1هَلا$2وَاللهْ');
  return s.trim();
}

module.exports = { speechText };
