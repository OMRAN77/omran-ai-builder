// المالك طلب حذف قائمة «المشاريع / بحث عن مشروع / حذف الكل». المزوّد قرأ ملفّين، ثمّ كتب خطّته
// («أحدّد العنصر… أقرأ العلامات… أتتبّع كلّ مراجعها قبل الحذف») وأنهى دوره بلا أيّ تعديل — فبدا الردّ
// تلاوةً للقواعد لا شغلًا، واضطرّ المالك أن يكرّر طلبه. السبب: حلقة الأدوات تنتهي حين يكتب النموذج نصًّا
// بلا استدعاء أداة، فالنموذج الكسول يتوقّف عند الخطّة.
// هنا: للمالك وحده، مرّة واحدة في الردّ — إن كان آخر نصّ خطّةً بصيغة «سأفعل/أقرأ/أتتبّع» بلا سؤال للمالك
// ولا رابط تنفيذ، يُعاد النموذج إلى الحلقة بتنبيه نظام قصير: نفّذ الآن بأدواتك.
'use strict';

const INTENT_RE = /(?:^|[\s.،,:؛\n(«-])(?:سأ|سوف\s|راح\s|رح\s|بـ?أ(?:قرأ|حذف|عدّ?ل|شيل|بحث|تتبّ?ع|فحص|رفع|نفّ?ذ)|خلّ?ني\s|دعني\s|الحين\s+(?:أ|ب)|الآن\s+(?:أ|س)|أ(?:قرأ|حدّ?د|تتبّ?ع|بحث|عدّ?ل|حذف|رفع|فحص|شيل|نفّ?ذ|راجع|تأكّ?د|بدأ|كمّ?ل|طبّ?ق)\s|let me\s|i(?:'ll| will| am going to)\s|next,? i\s)/i;
const ACTION_RE = /(?:احذف|حذف|شيل|امسح|عدّ?ل|غيّ?ر|صلّ?ح|أصلح|اصلح|ضيف|أضف|اضف|سوّ?ي?\s|نفّ?ذ|ارفع|حطّ?|انقل|كبّ?ر|صغّ?ر|خفّ?ف|بدّ?ل|ابن|اكتب\s+(?:كود|ملف)|fix|delete|remove|add|change|update|implement)/i;
const DONE_RE = /github\.com\/[^\s)]+\/(?:pull|commit)\/|✅|تمّ?\s+(?:الرفع|الحذف|التعديل|الدمج)/i;

/** هل توقّف النموذج عند خطّة بلا تنفيذ؟ صرف بلا شبكة (يُختبر وحده). */
function stalledPlan(text, opts) {
  const o = opts || {};
  const t = String(text || '').trim();
  if (!t || t.length > 1800) return false;
  if (/[?؟]/.test(t.slice(-220))) return false; // يسأل المالك — توقّف مشروع
  if (DONE_RE.test(t) || o.pushed) return false;
  if (!INTENT_RE.test(t)) return false;
  return !!(o.usedTools || ACTION_RE.test(String(o.ownerText || '')) || ACTION_RE.test(String(o.prevOwnerText || '')));
}

const CARRY_NOTE = '[تنبيه النظام — ليس من المالك]: ردّك السابق وصف ما ستفعله ثمّ توقّف بلا تنفيذ. نفّذ الآن بأدواتك في هذا الردّ نفسه '
  + '(اقرأ ما تحتاجه بـread_github ثمّ عدّل بـedit_github) — لا تُعِد الخطّة ولا تعتذر ولا تكرّر القواعد. '
  + 'إن كان ينقصك شيء لا تقدر عليه بأداة فقله في سطر واحد بالتحديد.';

/* v-owner-ui-shot (لقطة المالك ١٠ أكتوبر: «احذف هذا المكان» مع لقطة من التطبيق ← «جارٍ إنشاء الصورة»): المزوّد فهمها
   «امسح هذه المنطقة من الصورة» فاستدعى أداة الصور. لقطة المالك مع فعل تعديل وإشارة لعنصر، بلا كلمة صورة صريحة،
   = طلب تعديل التطبيق نفسه: أدوات الصور تُرفع من هذا الدور ويُضاف تنبيه قصير. */
const UI_VERB_RE = /(?:احذف|حذف|شيل|امسح|عدّ?ل|غيّ?ر|كبّ?ر|صغّ?ر|انقل|حرّ?ك|لوّ?ن|صلّ?ح|أصلح|اصلح|خبّ?ي|أخف|اخف|ضيف|أضف|اضف|وسّ?ط|ابعد|قرّ?ب|delete|remove|hide|move|fix|change)/i;
const UI_REF_RE = /(?:هذا|هذي|هذه|هاذا|هاذي|هنا|ذا\s|المكان|الزر|زر\s|زرّ|القائمة|قائمة|القسم|الشريط|الأيقونة|ايقونة|السهم|العنصر|البلوك|الخانة|الإطار|الاطار|الكلمة|النص|الشاشة|الواجهة|التطبيق|button|menu|section|element|icon|bar)/i;
const IMG_WORD_RE = /(?:الصور[ةه]|صورتي|صوره|صورة|الخلفي[ةه]\s+من|من\s+الصور|في\s+الصور|الشخص|الوجه|فوتوشوب|photo|picture|image|background\s+from)/i;
const ATTACH_NOTE_RE = /\n*\[(?:مرفقات|attachments|সংযুক্তি|adjuntos|mga attachment|pièces jointes|संलग्नक|lampiran|അറ്റാച്ച്മെന്റുകൾ|संलग्नकहरू|вложения|ekler|منسلکات|附件):\s[^\[\]\n]*\]\s*$/i;
function uiEditTurn(text) {
  /* v-owner-ui-shot-client: العميل يُلحق «[مرفقات: image.png]» بنصّ الدور — اسم الملفّ (image) كان يُقرأ كلمة صورة
     فيفشل الفحص. تُحذف هذه الملاحظة وحدها (عنوانها imagesAttachedNote بلغات التطبيق)، لا أيّ ملاحظة أخيرة بين قوسين:
     ملاحظة memory.png («[ملاحظة للنموذج: …]») تبقى فتمنع الفحص كما كانت. والطريق الأوّل قرار العميل (body.ownerUiShot في chat.js). */
  const s = String(text || '').replace(ATTACH_NOTE_RE, '');
  return !!s.trim() && s.length <= 600 && UI_VERB_RE.test(s) && UI_REF_RE.test(s) && !IMG_WORD_RE.test(s);
}
