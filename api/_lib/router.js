'use strict';

const RULES = [
  {
    intent: 'build_app',
    re: /(ابن|ابني|انشئ|أنشئ|سو لي|صمم لي|اصنع)\s+(لي\s+)?(تطبيق|موقع|صفحة|لوحة|نظام|متجر)/i,
  },
  {
    intent: 'image',
    re: /(ارسم|صمم لي صورة|اعمل صورة|ولّد صورة|شعار|لوقو|logo|صورة ل)/i,
  },
  {
    intent: 'live_info',
    re: /(مباراة|مباريات|نتيجة|نتائج|الدوري|فاز|هدف|سعر|اسعار|أسعار|الدولار|الذهب|البتكوين|طقس|الجو|خبر|اخبار|أخبار|الان|الآن|اليوم|امس|أمس|آخر|أحدث|من هو رئيس|من هو مدرب)/i,
  },
  {
    intent: 'code',
    re: /(كود|برمج|خطأ|error|bug|دالة|function|api|قاعدة بيانات)/i,
  },
];

/**
 * مرشّح سريع بلا نموذج — يغطي أغلب الحالات مجاناً.
 * @param {string} text
 * @returns {string|null}
 */
function quickIntent(text) {
  for (const r of RULES) if (r.re.test(text)) return r.intent;
  return null;
}

// ============================================================
// المصنّف بالنموذج — للحالات الغامضة فقط
// ============================================================

const CLASSIFY_PROMPT = [
  'صنّف رسالة المستخدم إلى نيّة واحدة:',
  '',
  'build_app — يريد إنشاء تطبيق أو موقع أو واجهة',
  'live_info — يحتاج معلومة متغيّرة: مباريات، أسعار، طقس، أخبار، مناصب حالية',
  'image — يريد صورة أو شعاراً',
  'code — سؤال برمجي أو خطأ في كود',
  'general — أي شيء آخر: شرح، رأي، دردشة، سؤال معرفي ثابت',
  '',
  'أجب بكلمة واحدة فقط من القائمة.',
].join('\n');

const VALID_INTENTS = ['build_app', 'live_info', 'image', 'code', 'general'];

/**
 * مصنّف بالنموذج — يُستدعى فقط إذا لم يطابق quickIntent.
 * @param {string} text
 * @param {(system: string, user: string) => Promise<string>} llm
 * @returns {Promise<string>}
 */
async function classify(text, llm) {
  const quick = quickIntent(text);
  if (quick) return quick;

  try {
    const raw = (await llm(CLASSIFY_PROMPT, text)).trim().toLowerCase();
    const found = VALID_INTENTS.find(function (i) { return raw.includes(i); });
    return found || 'general';
  } catch (_e) {
    return 'general';
  }
}

