'use strict';
/* v-text-emoji (مشتركة Max ١٦ أكتوبر، آيفون): صورة + «اكتب اشتقتلج و حط هذيل الإموجي 🤍🌷» كتبت على الصورة «اشتقتلج و حط / هذيل الإموجي»
   بلا الإيموجي. الجذر في المحلّل: جملة «وحط هذيل الإيموجي» لم تكن تعليمة فطُبعت، والإيموجي في آخر الرسالة يُرمى ذيلَ طلب (trimEnd).
   القرار: جملةٌ تسمّي الإيموجي أو قلبًا بعد النصّ تُقرأ ولا تُطبع، ورموزها خارج التنصيص تُلحق بالنصّ؛ بلا تسمية يبقى «🙏» ذيلًا يُرمى. */
const test = require('node:test');
const assert = require('node:assert/strict');
const { parseImageTextSpec: P } = require('../js/app-08-image-text.js');
const eq = (input, want) => { const s = P(input); for (const [k, v] of Object.entries(want)) assert.equal(s[k], v, input + ' ← ' + k); };

test('لقطة المشتركة: «اكتب اشتقتلج و حط هذيل الإموجي 🤍🌷» = «اشتقتلج 🤍🌷» بلا تعليمة ولا تعديل للصورة', () => {
  eq('اكتب اشتقتلج و حط هذيل الإموجي 🤍🌷', { wantsText: true, exactText: 'اشتقتلج 🤍🌷', visualEdit: null, positionAuto: true });
});

test('صيغ خليجيّة تسمّي الإيموجي: حط/ضيف/مع/بالإيموجي، قبل الرموز أو بعدها، وقبل الفعل', () => {
  for (const p of ['اكتب اشتقتلج وحط هذيل الايموجي 🤍🌷', 'اكتب اشتقتلج و ضيف الايموجي 🤍🌷', 'اكتب اشتقتلج مع الإيموجي 🤍🌷',
    'اكتب اشتقتلج وحط ايموجي 🤍🌷', 'اكتب اشتقتلج وحط معاها هالايموجي 🤍🌷', 'اكتب اشتقتلج مع هذي الايموجيات 🤍🌷', 'اكتب اشتقتلج بالإيموجي 🤍🌷',
    'اكتب اشتقتلج 🤍🌷 وحط الايموجي', 'اكتب «اشتقتلج» وحط هذيل الإيموجي 🤍🌷', 'حط هذيل الإموجي 🤍🌷 واكتب اشتقتلج'])
    eq(p, { wantsText: true, exactText: 'اشتقتلج 🤍🌷', visualEdit: null });
  eq('اكتب «حياتي 🤍» وحط الايموجي 🌷', { exactText: 'حياتي 🤍 🌷' });   /* ما في التنصيص حرفيّ، وما خارجه يُلحق */
});

test('الموضع واللون بعد جملة الإيموجي أو قبلها يُقرآن كما كانا', () => {
  eq('اكتب اشتقتلج على اليمين وحط هذيل الإموجي 🤍🌷', { exactText: 'اشتقتلج 🤍🌷', position: 'right-center', positionAuto: false });
  eq('اكتب على اليمين اشتقتلج وحط هذيل الإموجي 🤍🌷', { exactText: 'اشتقتلج 🤍🌷', position: 'right-center' });
  eq('اكتب اشتقتلج بالأحمر وحط هذيل الإموجي 🤍🌷', { exactText: 'اشتقتلج 🤍🌷', color: '#d32f2f' });
  eq('اكتب اشتقتلج وحط هذيل الايموجي 🤍🌷 على اليمين بالذهبي', { exactText: 'اشتقتلج 🤍🌷', position: 'right-center', color: '#f4cf65' });
});

test('القلب المطلوب بعد النصّ إيموجي بلونه، ولونه ليس لون الكتابة', () => {
  eq('اكتب اشتقتلج وحط قلب', { exactText: 'اشتقتلج ❤️' });
  eq('اكتب اشتقتلج و حط قلب ابيض', { exactText: 'اشتقتلج 🤍', color: '#ffffff' });
  eq('اكتب حياتي و قلب لون ابيض', { exactText: 'حياتي 🤍', color: '#ffffff' });
  eq('اكتب اشتقتلج وضيف ايموجي قلب ابيض', { exactText: 'اشتقتلج 🤍' });
  eq('اكتب اشتقتلج مع قلب', { exactText: 'اشتقتلج ❤️' });
  eq('اكتب تحت خوات بلون الأحمر و حط قلب ابيض', { exactText: 'خوات 🤍', color: '#d32f2f', position: 'bottom', positionAuto: false });
});

test('ما لا يطلب إيموجي يبقى كما هو: «قلب» في النصّ، والتنصيص، و«🙏» ذيل الطلب', () => {
  for (const t of ['حياتي وقلبي', 'عقل وقلب', 'يا قلبي', 'قلب الام', 'الروح والقلب']) eq('اكتب ' + t, { exactText: t });
  eq('اكتب امي لها قلب ابيض', { exactText: 'امي لها قلب' });            /* كما قبل الإصلاح — مصطلح «قلب أبيض» لا قلب */
  eq('اكتب مشكور اخوي 🙏', { exactText: 'مشكور اخوي' });
  eq('اكتب تحت الله يشفيج 🤍', { exactText: 'الله يشفيج', position: 'bottom' });
  eq('ارسم قلب واكتب حياتي', { exactText: 'حياتي', visualEdit: 'ارسم قلب' });   /* الجولة ٣: الرسم قبل الكتابة تعديل مشهد */
});

test('٦. مراجعة النقض: الإيموجي المسمّى بكلمة رمزُه، وحجم القلب لا يُطبع، والنفي يحذف، والإنجليزيّة، ورمز وسط النصّ في مكانه، و«في الفيديو» مع لقطة', () => {
  const X = (s) => P(s).exactText;
  assert.equal(X('اكتب حياتي وحط ايموجي ورد'), 'حياتي 🌹', 'كان «حياتي ورد»');
  assert.equal(X('اكتب صباح الخير وحط ايموجي شمس'), 'صباح الخير ☀️');
  assert.equal(X('اكتب صباح الخير ☀️ مع ايموجي ورد 🌹'), 'صباح الخير ☀️🌹', 'بلا تكرار 🌹');
  assert.equal(X('اكتب حبيبي وحط قلب صغير'), 'حبيبي ❤️', 'كان «حبيبي صغير ❤️»');
  assert.equal(X('اكتب حبيبي وحط قلب جنب الكلمة'), 'حبيبي ❤️');
  assert.equal(X('اكتب حياتي 🤍 بدون ايموجي'), 'حياتي', 'النفي: لا «بدون» ولا 🤍');
  assert.equal(X('اكتب حياتي ولا تحط ايموجي 🤍'), 'حياتي');
  assert.equal(X('write I love you ❤️ and add the emoji'), 'I love you ❤️');
  assert.equal(X('اكتب أحبك ❤️ يا أمي وحط ايموجي 🌹'), 'أحبك ❤️ يا أمي 🌹', 'رمز وسط نصّ المستخدم يبقى مكانه');
  /* الجواب الصادق على «اكتب … في الفيديو» يقترح لقطة بالطلب نفسه — فيُقرأ «في الفيديو/على المقطع» موضعًا كـ«في الصورة» */
  assert.equal(X('اكتب حياتي و قلب لون ابيض في الفيديو'), 'حياتي 🤍');
  assert.equal(X('اكتب حياتي على المقطع'), 'حياتي');
});
