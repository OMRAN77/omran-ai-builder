'use strict';
/* v-chat-doc-honesty (شكوى المالك ٣٠ سبتمبر: مستخدم أرفق صورة ورقة عمل وصحّح كلمة فيها، فردّ
   النموذج «تم تصحيح مكان كلمة أرنب ونقلها لسلة همزة القطع...» بلا أن يُنفَّذ أي تعديل فعليّ على
   الصورة — القاعدة القائمة (لا تُعِد رسم مستند بلا طلب صريح) صحيحة وتمنع edit_image هنا عن قصد،
   لكنها لم تكن تمنع صياغة الردّ النصّي بفعل ماضٍ يوهم بتعديل الصورة نفسها. */
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const chat = fs.readFileSync(path.join(__dirname, '..', 'api/_lib/chat.js'), 'utf8');

test('قاعدة الصورة المرفقة: صيغة صادقة إلزاميّة حين يجيب نصًّا بدل التعديل', () => {
  const i = chat.indexOf('[الصورة المرفقة — اقرأها أولًا، لا تعِد رسمها بلا طلب]');
  assert.ok(i > 0, 'القاعدة الأصليّة موجودة');
  const j = chat.indexOf('الصدق حين تجيب نصًّا بدل التعديل', i);
  assert.ok(j > i && j - i < 1200, 'بند الصدق يلي القاعدة مباشرة');
  const block = chat.slice(i, j + 800);
  assert.match(block, /اذكر الإجابة الصحيحة كحقيقة نصّية/, 'يطلب صياغة كحقيقة لا كفعل منجز');
  assert.match(block, /ممنوع منعًا باتًا صيغة فعل ماضٍ توحي بأنّك عدّلت الصورة نفسها فعليًّا/, 'يمنع صيغة الفعل الماضي الموهمة');
  assert.match(block, /نقلتها\/صحّحتها في الصورة\/مسحتها منها/, 'أمثلة الصيغة الممنوعة صريحة');
});
