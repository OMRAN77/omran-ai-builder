#!/usr/bin/env node
// Writes sw.js: the service worker that keeps every file of the game on the device, so that the game opens and plays
// with no internet at all (after it was opened once with internet). The list of files and a short hash of each is
// written into sw.js, so that a changed file changes sw.js, the browser fetches the new list, and only the files
// whose hash changed are downloaded again.
//
//   node tools/offline.cjs           write sw.js
//   node tools/offline.cjs --check   exit 1 if sw.js is not what it would write (tests/features.test.cjs runs this)

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..');
const DIRS = ['shared', 'styles', 'vendor', 'previews', 'icons'];
const FILES = ['index.html', 'manifest.webmanifest'];
const SKIP = /\.(md|txt|map|d\.ts)$|(^|\/)\./;

function walk(rel, out) {
  for (const name of fs.readdirSync(path.join(ROOT, rel)).sort()) {
    const r = rel + '/' + name, st = fs.statSync(path.join(ROOT, r));
    if (st.isDirectory()) walk(r, out); else if (!SKIP.test(r)) out.push(r);
  }
  return out;
}
const hash = (rel) => crypto.createHash('sha1').update(fs.readFileSync(path.join(ROOT, rel))).digest('hex').slice(0, 10);

function list() {
  const files = [...FILES, ...DIRS.flatMap((d) => walk(d, []))];
  return files.map((f) => [f === 'index.html' ? '' : f, hash(f)]);      // the first page is kept under the site's own address
}

function build() {
  const files = list();
  const version = crypto.createHash('sha1').update(files.map((f) => f.join(':')).join('\n')).digest('hex').slice(0, 10);
  return `// Generated by tools/offline.cjs: do not edit by hand (run «node tools/offline.cjs» after changing any game file).
// Keeps every file of the game on the device, so that it opens and plays with no internet: on a Wi-Fi without
// internet, a phone's hotspot, or no network at all. Files come from the device first; the site's rooms, saves and
// notes (api/) always go to the network and are never kept.
const VERSION = '${version}';
const CACHE = 'bw-' + VERSION;
const FILES = ${JSON.stringify(files)};
const READY = '__bw_ready';
const scope = () => self.registration.scope;

async function fill() {
  const cache = await caches.open(CACHE);
  const old = new Map();          // a file already kept by an older version with the same hash is copied, not downloaded again
  for (const k of await caches.keys()) {
    if (k === CACHE || !k.startsWith('bw-')) continue;
    const c = await caches.open(k);
    for (const req of await c.keys()) { const r = await c.match(req); if (r && r.headers.get('x-bw-hash')) old.set(req.url + '#' + r.headers.get('x-bw-hash'), r); }
  }
  let i = 0;
  const one = async () => {
    while (i < FILES.length) {
      const [rel, h] = FILES[i++], url = new URL(rel, scope()).href;
      const was = old.get(url + '#' + h);
      if (was) { await cache.put(url, was); continue; }
      const r = await fetch(url, { cache: 'no-cache' });
      if (!r.ok) throw new Error('could not keep ' + rel + ': ' + r.status);
      // a fresh response (the site may have answered through a redirect, which a navigation must not be given)
      await cache.put(url, new Response(await r.blob(), { headers: { 'Content-Type': r.headers.get('Content-Type') || 'application/octet-stream', 'x-bw-hash': h } }));
    }
  };
  await Promise.all([one(), one(), one()]);          // three at a time: the game that is starting meanwhile keeps the line and the phone
  await cache.put(new URL(READY, scope()).href, new Response(VERSION, { headers: { 'Content-Type': 'text/plain' } }));
}

self.addEventListener('install', (e) => { e.waitUntil(fill().then(() => self.skipWaiting())); });
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith('bw-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});

// the names a file may be asked by: «index.html» is the first page; «styles/x» and «styles/x/» are «styles/x/index.html»
function names(rel) {
  if (rel === 'index.html') return [''];
  if (rel === '' || rel.endsWith('.html') || /\\.[a-z0-9]+$/i.test(rel)) return [rel];
  return [rel, rel.replace(/\\/?$/, '/index.html')];
}
async function answer(req, rel) {
  const cache = await caches.open(CACHE);
  for (const n of names(rel)) { const r = await cache.match(new URL(n, scope()).href); if (r) return r; }
  try { return await fetch(req); } catch (e) {
    if (req.mode === 'navigate') { const r = await cache.match(scope()); if (r) return r; }
    throw e;
  }
}
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || !req.url.startsWith(scope())) return;
  const rel = req.url.slice(scope().length).replace(/[?#].*$/, '');
  if (rel.startsWith('api/') || rel === 'sw.js') return;          // rooms, saves and notes always go to the network
  e.respondWith(answer(req, rel));
});
`;
}

if (require.main === module) {
  const out = path.join(ROOT, 'sw.js'), text = build();
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
    if (now !== text) { console.error('sw.js is out of date: run «node tools/offline.cjs»'); process.exit(1); }
    console.log('sw.js is up to date (' + list().length + ' files)');
  } else { fs.writeFileSync(out, text); console.log('wrote sw.js: ' + list().length + ' files'); }
}
module.exports = { build, list };
